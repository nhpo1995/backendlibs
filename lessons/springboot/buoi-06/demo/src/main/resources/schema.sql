CREATE TABLE product_offerings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 3) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price BIGINT NOT NULL CHECK (price > 0),
    color VARCHAR(30) NOT NULL,
    status VARCHAR(8) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE product_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    brand VARCHAR(100) NOT NULL,
    power VARCHAR(30) NOT NULL
);

-- Quan hệ 1-1 của Buổi 4. Dữ liệu ví dụ dùng bộ bảng riêng.
CREATE TABLE single_detail (
    id BIGINT PRIMARY KEY,
    specification VARCHAR(100) NOT NULL
);
CREATE TABLE single_offering (
    id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    detail_id BIGINT UNIQUE REFERENCES single_detail(id)
);

CREATE TABLE product_offering_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_offering_id BIGINT NOT NULL REFERENCES product_offerings(id),
    product_detail_id BIGINT NOT NULL REFERENCES product_details(id),
    CONSTRAINT uq_offering_detail UNIQUE (product_offering_id, product_detail_id)
);
