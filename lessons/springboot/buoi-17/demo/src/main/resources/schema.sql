CREATE TABLE lab_members (
  id BIGINT PRIMARY KEY, first_name VARCHAR(60) NOT NULL, age INTEGER NOT NULL
);
CREATE TABLE products (
  id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, price BIGINT NOT NULL,
  color VARCHAR(15) NOT NULL, status VARCHAR(15) NOT NULL
);
CREATE TABLE lab_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
  name VARCHAR(40) UNIQUE NOT NULL, creator VARCHAR(40) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE lab_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
  username VARCHAR(40) UNIQUE NOT NULL, email VARCHAR(100) NOT NULL
);
CREATE TABLE lab_membership (
  account_id BIGINT REFERENCES lab_accounts(id),
  group_id BIGINT REFERENCES lab_groups(id),
  PRIMARY KEY (account_id, group_id)
);
