const { build } = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const root = path.resolve(__dirname, '..');
  const dest = path.join(root, 'assets/vendor/codemirror');
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['assets/editor-entry.js'],
    outfile: 'assets/vendor/codemirror/editor.js',
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: 'BackendCodeEditor',
    target: ['es2020'],
    metafile: true,
    legalComments: 'linked',
  });
  const packages = new Set();
  for (const input of Object.keys(result.metafile.inputs)) {
    const parts = input.replaceAll('\\', '/').split('/');
    const index = parts.lastIndexOf('node_modules');
    if (index < 0) continue;
    packages.add(parts[index + 1].startsWith('@') ? parts.slice(index + 1, index + 3).join('/') : parts[index + 1]);
  }
  const licenses = [...packages].sort().map(name => {
    const dir = path.join(root, 'node_modules', name);
    const metadata = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const filename = ['LICENSE', 'LICENSE.txt', 'LICENSE.md'].find(file => fs.existsSync(path.join(dir, file)));
    if (!filename) throw new Error(`Missing license for bundled package ${name}`);
    return `${name}@${metadata.version}\n${fs.readFileSync(path.join(dir, filename), 'utf8')}`;
  });
  fs.writeFileSync(path.join(dest, 'LICENSES.txt'), licenses.join('\n\n---\n\n'));
  fs.writeFileSync(path.join(dest, 'README.md'), '# CodeMirror editor bundle\n\nGenerated by `npm run build:editor`. Java, YAML and PowerShell modes; no CDN or runtime package loading.\n\nBundled upstream packages and MIT licenses are recorded in LICENSES.txt; exact versions in package-lock.json.\n');
  console.log('Built offline CodeMirror editor and bundled licenses.');
})().catch(error => { console.error(error); process.exitCode = 1; });
